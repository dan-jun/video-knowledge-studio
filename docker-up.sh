#!/usr/bin/env sh
set -eu
cd "$(dirname "$0")"

if ! sh ./install-agent.sh >/dev/null 2>&1; then
  echo "Warning: Agent bundle installation failed; Docker startup will continue." >&2
fi

DOCKER=$(command -v docker 2>/dev/null || true)
if [ -z "$DOCKER" ]; then
  for candidate in "/Applications/Docker.app/Contents/Resources/bin/docker"; do
    if [ -x "$candidate" ]; then
      DOCKER=$candidate
      break
    fi
  done
fi
if [ -z "$DOCKER" ]; then
  echo "Docker is not installed. Install Docker Desktop and retry." >&2
  exit 1
fi

ENV_FILE=".env.docker"
COMMAND=${1:-up}
if [ "$COMMAND" = "down" ]; then
  "$DOCKER" compose --env-file "$ENV_FILE" down
  exit 0
fi
if [ "$COMMAND" = "logs" ]; then
  "$DOCKER" compose --env-file "$ENV_FILE" logs --tail 120 -f
  exit 0
fi

if [ ! -f "$ENV_FILE" ]; then
  if command -v openssl >/dev/null 2>&1; then
    PASSWORD=$(openssl rand -hex 18)
  else
    PASSWORD=$(head -c 24 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 24)
  fi
  START_PORT=${VKS_DOCKER_PORT:-7870}
  PORT=$START_PORT
  ATTEMPT=0
  while [ "$ATTEMPT" -lt 30 ]; do
    if ! command -v nc >/dev/null 2>&1 || ! nc -z 127.0.0.1 "$PORT" >/dev/null 2>&1; then
      break
    fi
    PORT=$((PORT + 1))
    ATTEMPT=$((ATTEMPT + 1))
  done
  if [ "$ATTEMPT" -eq 30 ]; then
    echo "No free port in $START_PORT-$((START_PORT + 29))." >&2
    exit 1
  fi
  cat > "$ENV_FILE" <<EOF
# Generated by docker-up.sh. Do not commit this file.
VKS_PASSWORD=$PASSWORD
VKS_DOCKER_PORT=$PORT
VKS_AI_PROVIDER=mock
VKS_MODEL=gpt-4.1-mini
EOF
fi

"$DOCKER" compose --env-file "$ENV_FILE" up -d --build

PORT=$(sed -n 's/^VKS_DOCKER_PORT=//p' "$ENV_FILE" | tail -n 1)
ATTEMPT=0
while [ "$ATTEMPT" -lt 120 ]; do
  if curl -fsS "http://127.0.0.1:${PORT}/login.html" >/dev/null 2>&1; then
    URL="http://127.0.0.1:${PORT}/"
    PASSWORD=$(sed -n 's/^VKS_PASSWORD=//p' "$ENV_FILE" | tail -n 1)
    echo "Video Knowledge Studio: $URL"
    echo "Login password: $PASSWORD"
    if command -v open >/dev/null 2>&1; then open "$URL";
    elif command -v xdg-open >/dev/null 2>&1; then xdg-open "$URL" >/dev/null 2>&1 || true;
    fi
    exit 0
  fi
  ATTEMPT=$((ATTEMPT + 1))
  sleep 1
done

"$DOCKER" compose --env-file "$ENV_FILE" logs --tail 80
exit 1
