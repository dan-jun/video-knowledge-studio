def show(key):
    d = REVERSE.get(key)
    if not d:
        return False
    print(f"\n=== {key} ｜ {d['name']} ===")
    print(f"核心思想：{d['idea']}")
    print("适用特征（必须同时满足）：")
    for r in d["requires"]:
        print(f"  · {r}")
    print(f"为什么有效：{d['why']}")
    print("不能讲什么（以及为什么）：")
    for c in d["cannot"]:
        print(f"  ✗ {c}")
    print(f"最容易误用：{d['misuse']}")
    return True


def match(text):
    """按特征文字找候选手法——用于「我有个知识点，它具备哪些特征」的反查。"""
    hits = []
    for k, d in REVERSE.items():
        blob = " ".join(d["requires"]) + d["idea"] + d["why"]
        score = sum(1 for w in text.replace("，", " ").split() if w and w in blob)
        if score:
            hits.append((score, k, d["name"]))
    return sorted(hits, reverse=True)


def main():
    if "--list" in sys.argv:
        for k, d in REVERSE.items():
            print(f"{k:20s} {d['name']:22s} ｜ {d['idea'][:34]}")
        print(f"\n共 {len(REVERSE)} 条；缺的手法可继续补。")
        return 0
    if "--show" in sys.argv:
        i = sys.argv.index("--show")
        if i + 1 < len(sys.argv):
            return 0 if show(sys.argv[i + 1]) else 1
    if "--match" in sys.argv:
        i = sys.argv.index("--match")
        q = sys.argv[i + 1] if i + 1 < len(sys.argv) else ""
        for score, k, name in match(q)[:6]:
            print(f"  {score}  {k:20s} {name}")
        return 0
    print(__doc__)
    return 0


if __name__ == "__main__":
    sys.exit(main())
