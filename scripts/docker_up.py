#!/usr/bin/env python3
"""Build and run the local Docker deployment with a generated password."""

from __future__ import annotations

import argparse
import json
import os
import secrets
import shutil
import socket
import subprocess
import sys
import time
import urllib.error
import urllib.request
import webbrowser
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
ENV_FILE = ROOT / ".env.docker"


def docker_command() -> str:
    command = shutil.which("docker")
    if not command:
        candidates = []
        if os.name == "nt":
            local_app_data = os.environ.get("LOCALAPPDATA")
            program_files = os.environ.get("ProgramFiles")
            if local_app_data:
                candidates.append(
                    Path(local_app_data)
                    / "Programs"
                    / "DockerDesktop"
                    / "resources"
                    / "bin"
                    / "docker.exe"
                )
            if program_files:
                candidates.append(
                    Path(program_files) / "Docker" / "Docker" / "resources" / "bin" / "docker.exe"
                )
        elif sys.platform == "darwin":
            candidates.append(Path("/Applications/Docker.app/Contents/Resources/bin/docker"))
        command = next((str(path) for path in candidates if path.is_file()), None)
    if not command:
        raise SystemExit(
            "Docker is not installed. Install Docker Desktop, or run `python -m vks` without Docker."
        )
    return command


def port_open(port: int) -> bool:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
        sock.settimeout(0.25)
        return sock.connect_ex(("127.0.0.1", port)) == 0


def choose_port(start: int) -> int:
    for port in range(start, start + 30):
        if not port_open(port):
            return port
    raise SystemExit(f"no free port in {start}-{start + 29}")


def read_env() -> dict[str, str]:
    values = {}
    if not ENV_FILE.is_file():
        return values
    for raw in ENV_FILE.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if line and not line.startswith("#") and "=" in line:
            key, value = line.split("=", 1)
            values[key.strip()] = value.strip()
    return values


def ensure_env(port: int) -> tuple[dict[str, str], bool]:
    values = read_env()
    created = not values
    if not values.get("VKS_PASSWORD"):
        values["VKS_PASSWORD"] = secrets.token_urlsafe(18)
    values["VKS_DOCKER_PORT"] = str(port)
    values.setdefault("VKS_AI_PROVIDER", "mock")
    values.setdefault("VKS_MODEL", "gpt-4.1-mini")
    ENV_FILE.write_text(
        "# Generated by scripts/docker_up.py. Do not commit this file.\n"
        + "\n".join(f"{key}={value}" for key, value in values.items())
        + "\n",
        encoding="utf-8",
    )
    return values, created


def run_compose(docker: str, *args: str) -> int:
    command = [docker, "compose", "--env-file", str(ENV_FILE), *args]
    return subprocess.call(command, cwd=ROOT)


def healthy(port: int) -> bool:
    try:
        with urllib.request.urlopen(f"http://127.0.0.1:{port}/login.html", timeout=1) as response:
            return response.status == 200
    except (OSError, urllib.error.URLError):
        return False


def start(open_browser: bool) -> dict:
    docker = docker_command()
    current = read_env()
    requested = int(current.get("VKS_DOCKER_PORT") or os.environ.get("VKS_DOCKER_PORT") or 7870)
    port = choose_port(requested)
    values, created = ensure_env(port)
    result = run_compose(docker, "up", "-d", "--build")
    if result != 0:
        raise SystemExit(f"docker compose failed with exit code {result}")
    for _ in range(120):
        if healthy(port):
            break
        time.sleep(1)
    else:
        subprocess.call([docker, "compose", "--env-file", str(ENV_FILE), "logs", "--tail", "80"])
        raise SystemExit("container did not become healthy")
    url = f"http://127.0.0.1:{port}/"
    if open_browser:
        webbrowser.open(url)
    return {
        "ok": True,
        "url": url,
        "password": values["VKS_PASSWORD"],
        "env_file": str(ENV_FILE),
        "generated_password": created,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", nargs="?", choices=["up", "down", "logs"], default="up")
    parser.add_argument("--port", type=int, default=7870)
    parser.add_argument("--open", action="store_true")
    args = parser.parse_args()
    docker = docker_command()
    if args.command == "down":
        raise SystemExit(run_compose(docker, "down"))
    if args.command == "logs":
        raise SystemExit(run_compose(docker, "logs", "--tail", "120", "-f"))
    port = choose_port(args.port)
    values, created = ensure_env(port)
    result = run_compose(docker, "up", "-d", "--build")
    if result != 0:
        raise SystemExit(result)
    for _ in range(120):
        if healthy(port):
            break
        time.sleep(1)
    else:
        run_compose(docker, "logs", "--tail", "80")
        raise SystemExit("container did not become healthy")
    url = f"http://127.0.0.1:{port}/"
    if args.open:
        webbrowser.open(url)
    print(json.dumps({
        "ok": True,
        "url": url,
        "password": values["VKS_PASSWORD"],
        "env_file": str(ENV_FILE),
        "generated_password": created,
    }, ensure_ascii=True))


if __name__ == "__main__":
    main()
