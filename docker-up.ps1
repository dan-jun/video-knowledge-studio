param(
  [int]$Port = 0,
  [switch]$Open,
  [ValidateSet("up", "down", "logs")]
  [string]$Command = "up"
)

$ErrorActionPreference = "Stop"
Set-Location $PSScriptRoot

try {
  & (Join-Path $PSScriptRoot "install-agent.ps1") *> $null
} catch {
  Write-Warning "Agent bundle installation failed; Docker startup will continue."
}

$dockerCommand = (Get-Command docker -ErrorAction SilentlyContinue).Source
if (-not $dockerCommand) {
  $dockerCandidates = @(
    (Join-Path $env:LOCALAPPDATA "Programs\DockerDesktop\resources\bin\docker.exe"),
    (Join-Path $env:ProgramFiles "Docker\Docker\resources\bin\docker.exe")
  )
  $dockerCommand = $dockerCandidates |
    Where-Object { $_ -and (Test-Path -LiteralPath $_) } |
    Select-Object -First 1
}
if (-not $dockerCommand) {
  throw "Docker is not installed. Install Docker Desktop and retry."
}

$envPath = Join-Path $PSScriptRoot ".env.docker"
$values = @{}
if (Test-Path -LiteralPath $envPath) {
  Get-Content -LiteralPath $envPath | ForEach-Object {
    if ($_ -match '^\s*([^#][^=]*)=(.*)$') {
      $values[$matches[1].Trim()] = $matches[2].Trim()
    }
  }
}

if ($Command -eq "down") {
  & $dockerCommand compose --env-file $envPath down
  exit $LASTEXITCODE
}
if ($Command -eq "logs") {
  & $dockerCommand compose --env-file $envPath logs --tail 120 -f
  exit $LASTEXITCODE
}

function Test-Health([int]$candidate) {
  try {
    $response = Invoke-WebRequest -Uri "http://127.0.0.1:$candidate/login.html" -TimeoutSec 2
    return $response.StatusCode -eq 200 -and $response.Content -match "Video Knowledge Studio"
  } catch {
    return $false
  }
}

$savedPort = 0
if ($values["VKS_DOCKER_PORT"]) {
  [int]::TryParse($values["VKS_DOCKER_PORT"], [ref]$savedPort) | Out-Null
}
$existingHealthy = $savedPort -gt 0 -and (Test-Health $savedPort)

if (-not $values["VKS_PASSWORD"]) {
  $bytes = New-Object byte[] 18
  $rng = [Security.Cryptography.RandomNumberGenerator]::Create()
  try { $rng.GetBytes($bytes) } finally { $rng.Dispose() }
  $values["VKS_PASSWORD"] = [Convert]::ToBase64String($bytes).Replace("+", "-").Replace("/", "_").TrimEnd("=")
}

$startPort = if ($Port -gt 0) { $Port } elseif ($savedPort -gt 0) { $savedPort } else { 7870 }
$selectedPort = 0
if ($Port -eq 0 -and $existingHealthy) {
  $selectedPort = $savedPort
} else {
  for ($candidate = $startPort; $candidate -lt ($startPort + 30); $candidate++) {
    $client = New-Object Net.Sockets.TcpClient
    try {
      $task = $client.ConnectAsync("127.0.0.1", $candidate)
      if (-not $task.Wait(200)) {
        $selectedPort = $candidate
        break
      }
    } catch {
      $selectedPort = $candidate
      break
    } finally {
      $client.Dispose()
    }
  }
}
if ($selectedPort -eq 0) { throw "No free port in $startPort-$($startPort + 29)" }
$values["VKS_DOCKER_PORT"] = "$selectedPort"
if (-not $values["VKS_AI_PROVIDER"]) { $values["VKS_AI_PROVIDER"] = "mock" }
if (-not $values["VKS_MODEL"]) { $values["VKS_MODEL"] = "gpt-4.1-mini" }

$lines = @("# Generated by docker-up.ps1. Do not commit this file.")
$values.GetEnumerator() | Sort-Object Name | ForEach-Object { $lines += "$($_.Key)=$($_.Value)" }
$lines | Set-Content -LiteralPath $envPath -Encoding utf8

& $dockerCommand compose --env-file $envPath up -d --build
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

for ($i = 0; $i -lt 120; $i++) {
  if (Test-Health $selectedPort) {
    $url = "http://127.0.0.1:$selectedPort/"
    Write-Host "Video Knowledge Studio: $url"
    Write-Host "Login password: $($values['VKS_PASSWORD'])"
    Write-Host "Environment: $envPath"
    if ($Open) { Start-Process $url }
    exit 0
  }
  Start-Sleep -Seconds 1
}

& $dockerCommand compose --env-file $envPath logs --tail 80
throw "Container did not become healthy."
